import { Router } from "express";
import * as controller from "./practice.controller.js";
import { requireUser } from "../../http/auth.js";

const practiceRouter = Router();
practiceRouter.get("/practice", requireUser, controller.practice);
practiceRouter.get("/practice/review-items", requireUser, controller.reviewItems);
practiceRouter.post("/practice/review-items", requireUser, controller.createReviewItem);
practiceRouter.get("/practice/review-items/:itemId", requireUser, controller.reviewItem);
practiceRouter.patch("/practice/review-items/:itemId", requireUser, controller.updateReviewItem);
practiceRouter.delete("/practice/review-items/:itemId", requireUser, controller.deleteReviewItem);
practiceRouter.post("/practice/review-items/:itemId/answers", requireUser, controller.answerReviewItem);
practiceRouter.get("/study-tools", requireUser, controller.tools);
practiceRouter.get("/study-tools/:toolId", requireUser, controller.tool);
practiceRouter.get("/dictionary", requireUser, controller.dictionary);
practiceRouter.get("/vocabulary/sets", requireUser, controller.sets);
practiceRouter.post("/vocabulary/sets", requireUser, controller.createSet);
practiceRouter.get("/vocabulary/sets/:setId", requireUser, controller.getSet);
practiceRouter.patch("/vocabulary/sets/:setId", requireUser, controller.updateSet);
practiceRouter.delete("/vocabulary/sets/:setId", requireUser, controller.deleteSet);
practiceRouter.get("/vocabulary/sets/:setId/cards", requireUser, controller.cards);
practiceRouter.post("/vocabulary/sets/:setId/cards", requireUser, controller.createCard);
practiceRouter.get("/vocabulary/cards/:cardId", requireUser, controller.getCard);
practiceRouter.patch("/vocabulary/cards/:cardId", requireUser, controller.updateCard);
practiceRouter.delete("/vocabulary/cards/:cardId", requireUser, controller.deleteCard);
practiceRouter.post("/vocabulary/import/preview", requireUser, controller.previewImport);
practiceRouter.post("/vocabulary/import", requireUser, controller.importCards);
practiceRouter.get("/stories", controller.stories);
practiceRouter.get("/stories/:storyId", controller.getStory);
practiceRouter.get("/stories/:storyId/progress", requireUser, controller.getProgress);
practiceRouter.put("/stories/:storyId/progress", requireUser, controller.saveProgress);
practiceRouter.delete("/stories/:storyId/progress", requireUser, controller.resetProgress);
practiceRouter.get("/bookmarks", requireUser, controller.bookmarks);
practiceRouter.post("/bookmarks", requireUser, controller.createBookmark);
practiceRouter.patch("/bookmarks/:bookmarkId", requireUser, controller.updateBookmark);
practiceRouter.delete("/bookmarks/:bookmarkId", requireUser, controller.deleteBookmark);

export { practiceRouter };

export function isAppLanguage(value: unknown): value is AppLanguage {
  return value === "en" || value === "vi";
}

export function translateCopy(value: string, language: AppLanguage): string {
  if (language !== "vi") return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const key = value.trim().replace(/\s+/g, " ");
  const translated = VI[key] ?? DYNAMIC.map(([pattern, resolve]) => {
    const match = key.match(pattern);
    return match ? resolve(match) : undefined;
  }).find((candidate) => candidate !== undefined);
  return translated === undefined ? value : `${leading}${translated}${trailing}`;
}

export function setTranslationLanguage(language: AppLanguage): void {
  selectedLanguage = language;
}

export function translateCurrentCopy(value: string): string {
  return translateCopy(value, selectedLanguage);
}

